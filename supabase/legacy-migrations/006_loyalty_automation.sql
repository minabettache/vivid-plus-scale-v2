create or replace function public.get_member_points_multiplier(
  p_member_id bigint,
  p_at timestamptz default now()
)
returns numeric
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_tier_multiplier numeric := 1;
  v_rule_multiplier numeric := 1;
begin
  select coalesce(lt.points_multiplier, 1)
  into v_tier_multiplier
  from public.members m
  left join public.loyalty_tiers lt
    on lt.name = m.membership_level
   and lt.is_active = true
  where m.id = p_member_id;

  select coalesce(max(lr.multiplier), 1)
  into v_rule_multiplier
  from public.loyalty_rules lr
  where lr.is_active = true
    and lr.rule_type = 'points_multiplier'
    and lr.multiplier is not null
    and (
      lr.day_of_week is null
      or lr.day_of_week = extract(dow from p_at)::integer
    )
    and (
      lr.starts_at is null
      or lr.starts_at <= p_at
    )
    and (
      lr.ends_at is null
      or lr.ends_at >= p_at
    );

  return greatest(
    coalesce(v_tier_multiplier, 1),
    coalesce(v_rule_multiplier, 1)
  );
end;
$$;

create or replace function public.award_member_points(
  p_member_code text,
  p_points bigint,
  p_reason text,
  p_idempotency_key text default null,
  p_metadata jsonb default '{}'::jsonb
)
returns table (
  member_id bigint,
  member_name text,
  previous_balance bigint,
  new_balance bigint,
  ledger_id bigint
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_staff public.staff_users%rowtype;
  v_member public.members%rowtype;
  v_previous bigint;
  v_ledger_id bigint;
  v_multiplier numeric := 1;
  v_final_points bigint;
begin
  if auth.uid() is null then
    raise exception 'Authentication required'
      using errcode = '42501';
  end if;

  select *
  into v_staff
  from public.staff_users
  where auth_user_id = auth.uid()
    and is_active = true
  limit 1;

  if v_staff.id is null then
    raise exception 'Active staff account required'
      using errcode = '42501';
  end if;

  if p_points is null
    or p_points <= 0
    or p_points > 100000 then
    raise exception 'Points must be between 1 and 100000'
      using errcode = '22023';
  end if;

  if nullif(trim(p_member_code), '') is null then
    raise exception 'Member code is required'
      using errcode = '22023';
  end if;

  if nullif(trim(p_reason), '') is null then
    raise exception 'Reason is required'
      using errcode = '22023';
  end if;

  if p_idempotency_key is not null then
    select
      pt.member_id,
      m.full_name,
      pt.balance_after - pt.points_delta,
      pt.balance_after,
      pt.id
    into
      member_id,
      member_name,
      previous_balance,
      new_balance,
      ledger_id
    from public.points_transactions pt
    join public.members m
      on m.id = pt.member_id
    where pt.idempotency_key = p_idempotency_key;

    if found then
      return next;
      return;
    end if;
  end if;

  select *
  into v_member
  from public.members
  where is_active = true
    and (
      qr_code = trim(p_member_code)
      or id::text = trim(p_member_code)
    )
  for update;

  if v_member.id is null then
    raise exception 'Active member not found'
      using errcode = 'P0002';
  end if;

  v_multiplier :=
    public.get_member_points_multiplier(v_member.id, now());

  v_final_points :=
    greatest(1, round(p_points * v_multiplier)::bigint);

  v_previous := coalesce(v_member.points, 0);

  update public.members
  set
    points = v_previous + v_final_points,
    lifetime_points =
      coalesce(lifetime_points, 0) + v_final_points,
    total_visits =
      coalesce(total_visits, 0) + 1,
    last_visit_at = now()
  where id = v_member.id;

  insert into public.points_transactions (
    member_id,
    points_delta,
    balance_after,
    transaction_type,
    source_type,
    reason,
    staff_user_id,
    idempotency_key,
    metadata
  )
  values (
    v_member.id,
    v_final_points,
    v_previous + v_final_points,
    'award',
    'loyalty_engine',
    trim(p_reason),
    v_staff.id,
    p_idempotency_key,
    coalesce(p_metadata, '{}'::jsonb)
      || jsonb_build_object(
        'base_points', p_points,
        'multiplier', v_multiplier,
        'final_points', v_final_points,
        'membership_level', v_member.membership_level
      )
  )
  returning id into v_ledger_id;

  insert into public.audit_logs (
    actor_user_id,
    staff_user_id,
    action,
    entity_type,
    entity_id,
    old_values,
    new_values,
    metadata
  )
  values (
    auth.uid(),
    v_staff.id,
    'points.award',
    'member',
    v_member.id::text,
    jsonb_build_object(
      'points',
      v_previous
    ),
    jsonb_build_object(
      'points',
      v_previous + v_final_points
    ),
    jsonb_build_object(
      'base_points',
      p_points,
      'points_awarded',
      v_final_points,
      'multiplier',
      v_multiplier,
      'reason',
      trim(p_reason)
    )
    || coalesce(p_metadata, '{}'::jsonb)
  );

  member_id := v_member.id;
  member_name :=
    coalesce(v_member.full_name, 'VIVID+ Member');
  previous_balance := v_previous;
  new_balance := v_previous + v_final_points;
  ledger_id := v_ledger_id;

  return next;
end;
$$;

