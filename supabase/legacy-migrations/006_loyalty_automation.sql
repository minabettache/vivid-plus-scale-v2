create or replace function public.calculate_member_tier(
  p_lifetime_points bigint,
  p_total_visits bigint,
  p_total_spent numeric
)
returns text
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    (
      select lt.name
      from public.loyalty_tiers lt
      where lt.is_active = true
        and coalesce(p_lifetime_points, 0) >= lt.minimum_lifetime_points
        and coalesce(p_total_visits, 0) >= lt.minimum_visits
        and coalesce(p_total_spent, 0) >= lt.minimum_spend
      order by lt.rank desc
      limit 1
    ),
    'bronze'
  );
$$;

create or replace function public.sync_member_tier()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_tier text;
begin
  v_tier := public.calculate_member_tier(
    coalesce(new.lifetime_points, 0),
    coalesce(new.total_visits, 0),
    coalesce(new.total_spent, 0)
  );

  if new.membership_level is distinct from v_tier then
    new.membership_level := v_tier;
    new.tier_updated_at := now();
  end if;

  return new;
end;
$$;

